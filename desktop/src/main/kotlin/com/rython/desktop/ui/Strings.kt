class Lang(
    val code: String,
    val nativeName: String,
    private val map: Map<K, String>,
    val rtl: Boolean = false
) {
    fun t(key: K, vararg args: Any): String {
        val pattern = map[key] ?: key.name
        val text = if (args.isEmpty()) pattern else String.format(Locale.US, pattern, *args)
        // Latin runs inside an RTL sentence have to be isolated, otherwise the
        // renderer lays the words out in the wrong visual order.
        return if (rtl) Bidi.lri(text) else text
    }
}

